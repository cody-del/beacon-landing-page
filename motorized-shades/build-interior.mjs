// Bundle the existing styles without changing the exterior page's shared files.
import {readFile, writeFile} from 'node:fs/promises';
const root = new URL('./dist/', import.meta.url);
const sources = ['styles.css','beacon.css','reviews.css','service-area.css','gallery.css','hero-video.css','interior.css'];
const css = await Promise.all(sources.map(async name => {
  let text = await readFile(new URL(name, root), 'utf8');
  if (name === 'styles.css') text = text.replace(/@font-face\s*\{[^}]*\}/g, '');
  return `/* ${name} */\n${text}`;
}));
await writeFile(new URL('interior.bundle.css', root), '/* Generated by build-interior.mjs. Edit source styles, then rebuild. */\n' + css.join('\n'));
