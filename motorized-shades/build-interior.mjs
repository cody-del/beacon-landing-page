// Bundle the existing styles without changing the exterior page's shared files.
import {readFile, writeFile} from 'node:fs/promises';
const root = new URL('./dist/', import.meta.url);
const sources = ['styles.css','beacon.css','reviews.css','service-area.css','gallery.css','hero-video.css','interior.css'];
const css = await Promise.all(sources.map(async name => {
  let text = await readFile(new URL(name, root), 'utf8');
  if (name === 'styles.css') text = text.replace(/@font-face\s*\{[^}]*\}/g, '');
  return `/* ${name} */\n${text}`;
}));
const bundle = '/* Generated by build-interior.mjs. Edit source styles, then rebuild. */\n' + css.join('\n');
await writeFile(new URL('interior.bundle.css', root), bundle);
// Render this single landing page from its first HTML response without waiting
// for a stylesheet request. Keeping all styles avoids deferred layout shifts.
const page = new URL('index.html', root);
const html = await readFile(page, 'utf8');
const stylesheet = /<link rel="stylesheet" href="interior\.bundle\.css">|<style id="interior-styles">[\s\S]*?<\/style>/;
if (!stylesheet.test(html)) throw new Error('Interior stylesheet placeholder is missing');
await writeFile(page, html.replace(stylesheet, () => `<style id="interior-styles">${bundle}</style>`));
